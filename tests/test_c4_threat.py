"""Sabotage suite for 0.6 Phase 4: reef-c4.py (4.1: a fixture repository renders the expected elements; deleting a
container's directory -> contradicts; a hand-edited Mermaid export is detected; the structural lint), the
threat lint (4.3: a boundary crossing with no row fails; freshness), the plan-check freshness demand, and the
security gates as proposals (4.5: defaults pinned for a new project; an upgrade leaves gates.extra untouched)."""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C4 = os.path.join(ROOT, "scripts", "reef-c4.py")
THREAT = os.path.join(ROOT, "scripts", "reef-threat.py")
CHECK = os.path.join(ROOT, "scripts", "reef-plan-check.py")
INIT = os.path.join(ROOT, "scripts", "reef-init.py")


def write(root, rel, text):
    p = os.path.join(root, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text)
    return p


def git(d, *a):
    return subprocess.run(["git", "-C", d, "-c", "user.email=t@t", "-c", "user.name=t", *a], check=True, capture_output=True, text=True).stdout


def fixture():
    """A Node web app: Express routes, a React page, Postgres via pg, Stripe, a compose redis service."""
    d = tempfile.mkdtemp(prefix="reef-c4.")
    subprocess.run(["git", "init", "-q", "-b", "main", d], check=True)
    write(d, "package.json", json.dumps({"name": "shop", "dependencies": {"express": "4", "pg": "8", "stripe": "14", "react": "18"}}))
    write(d, "src/server.js", "const app = require('express')();\napp.get('/orders', (req, res) => res.json([]));\n")
    write(d, "src/App.tsx", "export default function App() { return <div/>; }\n")
    write(d, "docker-compose.yml", "services:\n  web:\n    image: node\n  redis:\n    image: redis\n")
    write(d, ".reef/config.json", json.dumps({"gates": {"full": "true"}}))
    git(d, "add", "-A")
    git(d, "commit", "-qm", "init")
    return d


def c4(d, *args):
    return subprocess.run([sys.executable, C4, *args, "--repo", d], capture_output=True, text=True)


class C4Model(unittest.TestCase):
    def test_fixture_renders_expected_elements_and_lint_passes(self):
        d = fixture()
        r = c4(d, "generate", "--write")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        dsl = open(os.path.join(d, "reef", "architecture", "workspace.dsl")).read()
        for needle in ('api = container "shop API" "HTTP routes"', "# proof: src/server.js", 'web = container "shop web"', "# proof: src/App.tsx",
                       'postgres = container "Postgres" "via pg" { tags "Database" }', 'stripe = softwareSystem "Stripe"', 'redis = container "redis" "compose service"',
                       "systemContext system", "container system"):
            self.assertIn(needle, dsl, needle)
        self.assertIn('operator = person "Operator"', dsl)
        self.assertIn('"Inferred"', dsl, "the operator is inferred, and says so")
        self.assertEqual(c4(d, "lint").returncode, 0)
        ctx = open(os.path.join(d, "reef", "architecture", "context.md")).read()
        self.assertIn("generated by scripts/reef-c4.py", ctx)
        self.assertIn('system --> stripe["Stripe"]', ctx)
        git(d, "add", "-A")
        git(d, "commit", "-qm", "model")
        r = c4(d, "--diff")
        self.assertEqual(r.returncode, 0, r.stdout)

    def test_every_third_party_compose_service_is_a_container_the_app_itself_is_not(self):
        """2026-10-18, the trial: a Mailpit service added to compose.yaml was invisible to the generator (fixed name list),
        so its DSL line was hand-added and --diff then contradicted it. A service with a third-party image is a
        container proven by the compose file; one built from the repo or on a bare runtime image is the app itself."""
        d = fixture()
        write(d, "docker-compose.yml", "services:\n  web:\n    image: node:22\n  app:\n    build: .\n    image: shop/app\n"
                                       "  db:\n    image: postgres:16\n  mailpit:\n    image: axllent/mailpit:v1.31.6\n    ports:\n      - \"127.0.0.1:1025:1025\"\n")
        r = c4(d, "generate", "--write")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        dsl = open(os.path.join(d, "reef", "architecture", "workspace.dsl")).read()
        self.assertIn('mailpit = container "mailpit" "compose service"', dsl)
        self.assertIn("# proof: docker-compose.yml", dsl)
        self.assertNotIn('app = container "app"', dsl, "built from this repository: the app itself")
        self.assertEqual(dsl.count('container "shop web"'), 1, "`web: image: node` is the app's runtime, not a second web container")
        self.assertIn('db = container "db" "compose service" { tags "Database" }', dsl, "as before: a db service is a store")
        git(d, "add", "-A")
        git(d, "commit", "-qm", "model")
        self.assertEqual(c4(d, "--diff").returncode, 0, "the generated model has nothing hand-added, so --diff is clean")

    def test_deleting_a_container_contradicts_and_a_new_one_is_missing(self):
        d = fixture()
        c4(d, "generate", "--write")
        git(d, "add", "-A")
        git(d, "commit", "-qm", "model")
        shutil.rmtree(os.path.join(d, "src"))
        write(d, "src/cli.py", "print(1)\n")
        r = c4(d, "--diff")
        self.assertEqual(r.returncode, 1)
        self.assertIn("contradicts: shop API", r.stdout)
        write(d, "package.json", json.dumps({"name": "shop", "dependencies": {"express": "4", "pg": "8", "stripe": "14", "react": "18", "kafkajs": "2"}}))
        r = c4(d, "--diff")
        self.assertIn("missing: Kafka", r.stdout)

    def test_hand_edited_mermaid_export_is_drift(self):
        d = fixture()
        c4(d, "generate", "--write")
        git(d, "add", "-A")
        git(d, "commit", "-qm", "model")
        p = os.path.join(d, "reef", "architecture", "container.md")
        with open(p, "a") as f:
            f.write("\n")
        with open(p) as f:
            t = f.read()
        write(d, "reef/architecture/container.md", t.replace('api["shop API"]', 'api["shop API (edited by hand)"]'))
        r = c4(d, "--diff")
        self.assertEqual(r.returncode, 1)
        self.assertIn("container.md differs from the export", r.stdout)

    def test_lint_catches_broken_dsl(self):
        d = fixture()
        p = write(d, "bad.dsl", 'workspace "x" {\n  model {\n    a = person "A"\n    a = person "A again"\n    a -> ghost "uses"\n  }\n')
        r = c4(d, "lint", p)
        self.assertEqual(r.returncode, 1)
        self.assertIn("unbalanced braces", r.stdout)
        self.assertIn("duplicate identifiers: a", r.stdout)
        self.assertIn("unknown element 'ghost'", r.stdout)
        self.assertIn("no `views {` block", r.stdout)


TM_GOOD = """# Threat model

```mermaid
flowchart LR
  subgraph internet
    operator
  end
  subgraph product
    api --> postgres
  end
  operator --> api
  api --> stripe
```

| crossing | STRIDE | threat | mitigation | proof |
|---|---|---|---|---|
| operator -> api | S | a stranger calls the API as an operator | bearer token middleware (src/auth.js) | `test_orders_requires_token` |
| api -> postgres | I | a dump leaks personal data | column encryption for emails | `test_email_column_encrypted` |
| api -> stripe | T | a forged webhook marks an order paid | signature check (src/webhooks.js) | `test_webhook_signature_rejected` |
"""


class ThreatLint(unittest.TestCase):
    def setUp(self):
        self.d = fixture()
        write(self.d, "src/redis.js", "")
        c4(self.d, "generate", "--write")
        # the fixture model crosses operator -> api, api -> postgres, api -> stripe (+ redis in the chain)
        dsl = open(os.path.join(self.d, "reef", "architecture", "workspace.dsl")).read()
        self.crossings = subprocess.run([sys.executable, "-c",
                                         "import importlib.machinery as m, importlib.util as u, sys; l=m.SourceFileLoader('t', sys.argv[1]); s=u.spec_from_loader('t', l); t=u.module_from_spec(s); l.exec_module(t); print('\\n'.join(t.crossings(open(sys.argv[2]).read())))",
                                         THREAT, os.path.join(self.d, "reef", "architecture", "workspace.dsl")], capture_output=True, text=True).stdout.split()

    def threat(self, *args):
        return subprocess.run([sys.executable, THREAT, *args, "--repo", self.d], capture_output=True, text=True)

    def test_crossing_without_a_row_fails_and_full_table_passes(self):
        write(self.d, "reef/architecture/threat-model.md", TM_GOOD)
        r = self.threat("lint")
        self.assertEqual(r.returncode, 1, "the fixture has more crossings than the three rows")
        self.assertIn("has no STRIDE row", r.stdout)
        dsl = open(os.path.join(self.d, "reef", "architecture", "workspace.dsl")).read()
        rows = "".join(f"| {c} | D | load knocks it over | rate limit | `test_rate_limit` |\n" for c in
                       [l.strip() for l in subprocess.run([sys.executable, "-c",
                                                            "import importlib.machinery as m, importlib.util as u, sys; l=m.SourceFileLoader('t', sys.argv[1]); s=u.spec_from_loader('t', l); t=u.module_from_spec(s); l.exec_module(t); print('\\n'.join(t.crossings(open(sys.argv[2]).read())))",
                                                            THREAT, os.path.join(self.d, "reef", "architecture", "workspace.dsl")], capture_output=True, text=True).stdout.splitlines() if l.strip()])
        write(self.d, "reef/architecture/threat-model.md", TM_GOOD + rows)
        r = self.threat("lint")
        self.assertEqual(r.returncode, 0, r.stdout)

    def test_row_without_proof_or_with_bare_acceptance_fails(self):
        base = TM_GOOD.replace("| `test_orders_requires_token` |", "| we checked it |")
        write(self.d, "reef/architecture/threat-model.md", base)
        r = self.threat("lint")
        self.assertIn("names no proving test or command", r.stdout)
        write(self.d, "reef/architecture/threat-model.md", TM_GOOD.replace("| bearer token middleware (src/auth.js) | `test_orders_requires_token` |", "| accepted: | |"))
        self.assertIn("accepts the risk without a reason", self.threat("lint").stdout)
        write(self.d, "reef/architecture/threat-model.md", TM_GOOD.replace("| bearer token middleware (src/auth.js) | `test_orders_requires_token` |", "| accepted: internal network only, owner footnote 3 | |"))
        self.assertNotIn("operator -> api", "\n".join(l for l in self.threat("lint").stdout.splitlines() if "no proving" in l or "accepts" in l))

    def test_unmitigated_rows_print_as_found_queue_rows(self):
        write(self.d, "reef/architecture/threat-model.md", TM_GOOD.replace("| bearer token middleware (src/auth.js) | `test_orders_requires_token` |", "| TODO | |"))
        r = self.threat("rows")
        self.assertIn("| found |", r.stdout)
        self.assertIn("touches: [auth]", r.stdout)
        self.assertIn("1 unmitigated row(s)", r.stdout)

    def test_plan_check_demands_a_fresh_threat_model_for_a_critical_auth_task(self):
        write(self.d, "reef/architecture/architecture.md", "# arch\n")
        write(self.d, "CLAUDE.md", "# brief\n")
        write(self.d, ".reef/version", "0.6.0\n")
        os.makedirs(os.path.join(self.d, "tasks", "done"), exist_ok=True)
        write(self.d, "tasks/001-auth.md", "---\nid: 1\nfeature: demo\nstatus: pending\ncomplexity: design\neffort: high\nblocked-by: []\nresources: []\ntier: critical\ntouches: [auth]\nverify: judge\nattempts: 0\ndispatches: 0\nlast_failure_sig: \"\"\n---\n# 1\n\n## Scope\nx\n\n## Decision\nhuman words\n\n## Acceptance Criteria\n- test_auth_token_required goes red first\n\n## Log\n")
        git(self.d, "add", "-A")
        git(self.d, "commit", "-qm", "arch")
        r = subprocess.run([sys.executable, CHECK, self.d], capture_output=True, text=True)
        self.assertEqual(r.returncode, 1)
        self.assertIn("threat-model.md is missing", r.stdout)
        write(self.d, "reef/architecture/threat-model.md", TM_GOOD)
        git(self.d, "add", "-A")
        git(self.d, "commit", "-qm", "threat model")
        r = subprocess.run([sys.executable, CHECK, self.d], capture_output=True, text=True)
        self.assertNotIn("threat-model.md", r.stdout)
        self.assertEqual(self.threat("fresh").returncode, 0)


class SecurityGatesAsProposals(unittest.TestCase):
    def test_new_project_gets_release_gates_and_an_upgrade_only_a_proposal(self):
        d = tempfile.mkdtemp(prefix="reef-init-sec.")
        write(d, "package.json", json.dumps({"name": "x", "scripts": {"test": "echo t"}}))
        subprocess.run(["git", "init", "-q", d], check=True)
        r = subprocess.run([sys.executable, INIT, "--root", d], capture_output=True, text=True)
        cfg = json.loads(open(os.path.join(d, ".reef", "config.json")).read())
        self.assertEqual(cfg["gates"]["release"], {"c4": "python3 scripts/reef-c4.py --diff",
                                                   "secret-scan": "command -v gitleaks >/dev/null 2>&1 || exit 77; gitleaks detect --source . --log-opts=--all --no-banner",
                                                   "audit": "npm audit --audit-level=high",
                                                   # 0.7.2 (ai-coach, item 12): a deterministic injection scan per stack
                                                   "injection": "command -v semgrep >/dev/null 2>&1 || exit 77; semgrep scan --config p/owasp-top-ten --config p/typescript --error"})
        ci = open(os.path.join(d, ".github", "workflows", "ci.yml")).read()
        self.assertIn("--ci --release", ci)
        self.assertIn("gitleaks", ci)
        self.assertIn("pip install semgrep", ci, "CI installs the scanner like gitleaks")
        env = dict(os.environ, PATH=tempfile.mkdtemp(prefix="reef-nosemgrep."))   # a PATH without semgrep (and without anything else)
        r = subprocess.run(["/bin/sh", "-c", cfg["gates"]["release"]["injection"]], capture_output=True, text=True, env=env)
        self.assertEqual(r.returncode, 77, "semgrep missing is a SKIP (77), never a pass")
        # an existing 0.5 project: gates.extra untouched, release gates only PROPOSED
        d5 = tempfile.mkdtemp(prefix="reef-init-sec5.")
        write(d5, "pyproject.toml", "[project]\nname='y'\n")
        write(d5, "docs/queue.md", "# q\n")
        write(d5, ".reef/config.json", json.dumps({"gates": {"full": "pytest -q", "extra": {"build": "make"}}}))
        subprocess.run(["git", "init", "-q", d5], check=True)
        r = subprocess.run([sys.executable, INIT, "--root", d5], capture_output=True, text=True)
        cfg5 = json.loads(open(os.path.join(d5, ".reef", "config.json")).read())
        self.assertEqual(cfg5["gates"]["extra"], {"build": "make"})
        self.assertNotIn("release", cfg5["gates"], "an upgrade never adds a gate that could turn CI red")
        self.assertTrue(os.path.isfile(os.path.join(d5, ".git", "reef", "proposed", "gates.release.json")))
        self.assertIn("gates.release", r.stdout)
        self.assertIn("exit 77", r.stdout)


